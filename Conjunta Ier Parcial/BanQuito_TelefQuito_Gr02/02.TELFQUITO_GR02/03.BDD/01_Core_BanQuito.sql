-- =====================================================================
-- BANQUITO - Core bancario + modulo de credito  (esquema: core)
-- Examen Complexivo Practico - Modulo de Credito  | Grupo GR02
-- Modelo del Core segun enunciado: CLIENTE, CUENTA, MOVIMIENTO
-- + modulo de credito (en el mismo esquema): CREDITO, AMORTIZACION
-- Las fechas de los movimientos son RELATIVAS a CURDATE(): vuelva a
-- ejecutar este script el dia de la defensa para que los clientes sean
-- sujetos de credito (deposito en el ultimo mes, promedios 3 meses).
-- =====================================================================
DROP DATABASE IF EXISTS core;
CREATE DATABASE core CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE core;

CREATE TABLE cliente (
  COD_CLIENTE      INT NOT NULL AUTO_INCREMENT,
  CEDULA           VARCHAR(100) NOT NULL,
  NOMBRE           VARCHAR(100) NOT NULL,
  GENERO           VARCHAR(1) NOT NULL,
  FECHA_NACIMIENTO DATE NOT NULL,
  PRIMARY KEY (COD_CLIENTE)
) ENGINE=InnoDB;

CREATE TABLE cuenta (
  NUM_CUENTA  VARCHAR(8) NOT NULL,
  COD_CLIENTE INT NOT NULL,
  SALDO       NUMERIC(10,2) NOT NULL,
  PRIMARY KEY (NUM_CUENTA),
  CONSTRAINT COD_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES cliente (COD_CLIENTE)
) ENGINE=InnoDB;

CREATE TABLE movimiento (
  COD_MOVIMIENTO INT NOT NULL AUTO_INCREMENT,
  NUM_CUENTA     VARCHAR(8) NOT NULL,
  TIPO           VARCHAR(3) NOT NULL COMMENT 'DEP = deposito, RET = retiro',
  VALOR          NUMERIC(10,2) NOT NULL,
  FECHA          DATE NOT NULL,
  PRIMARY KEY (COD_MOVIMIENTO),
  CONSTRAINT NUM_CUENTA FOREIGN KEY (NUM_CUENTA) REFERENCES cuenta (NUM_CUENTA)
) ENGINE=InnoDB;

-- ---- Modulo de credito (mismo esquema del core) ----
CREATE TABLE credito (
  COD_CREDITO  INT NOT NULL AUTO_INCREMENT,
  COD_CLIENTE  INT NOT NULL,
  MONTO        DECIMAL(10,2) NOT NULL,
  PLAZO_MESES  INT NOT NULL,
  TASA_INTERES DECIMAL(5,2) NOT NULL,
  FECHA_INICIO DATE NOT NULL,
  ACTIVO       INT NOT NULL COMMENT '1 = credito vigente',
  PRIMARY KEY (COD_CREDITO),
  CONSTRAINT FK_CREDITO_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES cliente (COD_CLIENTE)
) ENGINE=InnoDB;

CREATE TABLE amortizacion (
  COD_AMORTIZACION INT NOT NULL AUTO_INCREMENT,
  COD_CREDITO      INT NOT NULL,
  CUOTA            INT NOT NULL,
  VALOR_CUOTA      DECIMAL(10,2) NOT NULL,
  INTERES_PAGADO   DECIMAL(10,2) NOT NULL,
  CAPITAL_PAGADO   DECIMAL(10,2) NOT NULL,
  SALDO            DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (COD_AMORTIZACION),
  CONSTRAINT FK_AMORTIZACION_CREDITO FOREIGN KEY (COD_CREDITO) REFERENCES credito (COD_CREDITO)
) ENGINE=InnoDB;

